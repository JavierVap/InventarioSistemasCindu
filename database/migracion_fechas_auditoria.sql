-- Migracion para MariaDB 10.4.
-- Las fechas historicas quedan en NULL porque el volcado no contiene esos datos.
-- Los registros nuevos reciben fechas automaticamente despues de aplicar la migracion.

ALTER TABLE departamentos
    ADD COLUMN IF NOT EXISTS creado_en TIMESTAMP NULL DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS actualizado_en TIMESTAMP NULL DEFAULT NULL;

ALTER TABLE departamentos
    MODIFY COLUMN creado_en TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
    MODIFY COLUMN actualizado_en TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP;

ALTER TABLE insumos
    ADD COLUMN IF NOT EXISTS creado_en TIMESTAMP NULL DEFAULT NULL,
    ADD COLUMN IF NOT EXISTS actualizado_en TIMESTAMP NULL DEFAULT NULL;

ALTER TABLE insumos
    MODIFY COLUMN creado_en TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP,
    MODIFY COLUMN actualizado_en TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP;

ALTER TABLE usuarios
    ADD COLUMN IF NOT EXISTS actualizado_en TIMESTAMP NULL DEFAULT NULL;

ALTER TABLE usuarios
    MODIFY COLUMN actualizado_en TIMESTAMP NULL DEFAULT CURRENT_TIMESTAMP
        ON UPDATE CURRENT_TIMESTAMP;
